import os
import tempfile
from pathlib import Path

import networkx as nx
import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from graph_builder import load_and_build_graph
from relationship_analysis import analyze_relationships

st.set_page_config(
    page_title="Fraud Relationship Detection",
    page_icon="🔎",
    layout="wide",
)

st.title("Fraud Transaction Relationship Detection System")
st.caption("Multi-entity graph analysis (Accounts, Devices, IPs) & fraud screening")

# 1. Dataset Selection (Built-in datasets or CSV upload)
st.sidebar.header("1. Data Source")
data_choice = st.sidebar.radio(
    "Choose dataset:",
    [
        "Synthetic Dataset (transactions.csv)",
        "PaySim Sample (data/processed/paysim_sample.csv)",
        "Upload Custom CSV",
    ],
)

temp_path = None
if data_choice == "Upload Custom CSV":
    uploaded = st.sidebar.file_uploader("Upload CSV", type=["csv"])
    if uploaded is None:
        st.info("Please upload a CSV file in the sidebar or select one of the built-in datasets.")
        st.stop()
    with tempfile.NamedTemporaryFile(suffix=".csv", delete=False) as tmp:
        tmp.write(uploaded.getvalue())
        temp_path = tmp.name
    active_csv = temp_path
elif data_choice == "PaySim Sample (data/processed/paysim_sample.csv)":
    active_csv = "data/processed/paysim_sample.csv"
else:
    active_csv = "transactions.csv"

# 2. Run Teammates' Pipeline
try:
    graph, df = load_and_build_graph(active_csv)
    analyze_relationships(active_csv)  # Generates outputs/account_risk.csv
except Exception as e:
    st.error(f"Error processing dataset: {e}")
    if temp_path and os.path.exists(temp_path):
        os.unlink(temp_path)
    st.stop()
finally:
    if temp_path and os.path.exists(temp_path):
        os.unlink(temp_path)

# Load the account risk report generated by relationship_analysis.py
risk_report_path = Path("outputs/account_risk.csv")
account_risk_df = pd.read_csv(risk_report_path) if risk_report_path.exists() else pd.DataFrame()

# 3. Sidebar Filters
st.sidebar.header("2. Investigation Filters")
min_amount = st.sidebar.number_input("Minimum Amount Filter", min_value=0.0, value=0.0, step=500.0)
only_fraud = st.sidebar.checkbox("Show only labelled fraud (is_fraud == 1)", value=False)
search_account = st.sidebar.text_input("Search Account / Device / IP").strip()

filtered_df = df[df["amount"] >= min_amount].copy()
if only_fraud:
    filtered_df = filtered_df[filtered_df["is_fraud"] == 1]

if search_account:
    mask = (
        filtered_df["sender_id"].astype(str).str.contains(search_account, case=False, na=False)
        | filtered_df["receiver_id"].astype(str).str.contains(search_account, case=False, na=False)
        | filtered_df["device_id"].astype(str).str.contains(search_account, case=False, na=False)
        | filtered_df["ip_address"].astype(str).str.contains(search_account, case=False, na=False)
    )
    filtered_df = filtered_df[mask]

# 4. Top KPI Metrics
c1, c2, c3, c4 = st.columns(4)
c1.metric("Total Transactions", len(df))
c2.metric("Fraud-Labelled Txns", int((df["is_fraud"] == 1).sum()))
c3.metric("Graph Nodes (Accounts + Entities)", graph.number_of_nodes())
c4.metric("Graph Relationships (Edges)", graph.number_of_edges())

# 5. Transactions Table & Export
st.subheader("Filtered Transactions")
st.dataframe(filtered_df, use_container_width=True)
st.download_button(
    "Download Filtered Transactions (CSV)",
    data=filtered_df.to_csv(index=False).encode("utf-8"),
    file_name="filtered_transactions.csv",
    mime="text/csv",
)

# 6. Account Risk & Shared Entity Summary (from relationship_analysis.py)
st.subheader("Account Risk & Shared Device/IP Report")
if not account_risk_df.empty:
    st.dataframe(
        account_risk_df.sort_values(by=["review_flag", "total_amount"], ascending=[False, False]),
        use_container_width=True,
    )
    st.download_button(
        "Download Account Risk Report (CSV)",
        data=account_risk_df.to_csv(index=False).encode("utf-8"),
        file_name="account_risk_report.csv",
        mime="text/csv",
    )

# 7. Interactive Multi-Entity Relationship Network (Plotly)
st.subheader("Interactive Entity Relationship Network")
st.caption("Blue = Account | Orange = Device | Purple = IP Address | Red = Flagged Fraud Account")

if graph.number_of_nodes() > 0:
    # Cap visualization size at 150 nodes so large Kaggle samples stay smooth
    nodes_to_show = list(graph.nodes())[:150]
    viz_graph = graph.subgraph(nodes_to_show)
    pos = nx.spring_layout(viz_graph, seed=42)

    edge_x, edge_y = [], []
    for u, v in viz_graph.edges():
        x0, y0 = pos[u]
        x1, y1 = pos[v]
        edge_x.extend([x0, x1, None])
        edge_y.extend([y0, y1, None])

    edge_trace = go.Scatter(
        x=edge_x,
        y=edge_y,
        mode="lines",
        line=dict(width=1, color="#95a5a6"),
        hoverinfo="none",
    )

    flagged_accounts = set()
    if not account_risk_df.empty:
        flagged_accounts = set(
            account_risk_df[account_risk_df["review_flag"] == "Review"]["account_id"].astype(str)
        )

    node_x, node_y, node_labels, node_hover, node_colors = [], [], [], [], []
    for node, attrs in viz_graph.nodes(data=True):
        x, y = pos[node]
        node_x.append(x)
        node_y.append(y)
        node_type = attrs.get("node_type", "account")
        node_labels.append(str(node) if viz_graph.number_of_nodes() <= 40 else "")

        if node_type == "uses_device":
            color = "#f39c12"  # Orange for Device
        elif node_type == "uses_ip":
            color = "#9b59b6"  # Purple for IP
        elif str(node) in flagged_accounts:
            color = "#e74c3c"  # Red for Account needing review
        else:
            color = "#3498db"  # Blue for Normal Account

        node_colors.append(color)
        node_hover.append(
            f"Entity: {node}<br>"
            f"Type: {node_type}<br>"
            f"Connections: {viz_graph.degree(node)}"
        )

    node_trace = go.Scatter(
        x=node_x,
        y=node_y,
        mode="markers+text" if viz_graph.number_of_nodes() <= 40 else "markers",
        text=node_labels,
        textposition="top center",
        hovertext=node_hover,
        hoverinfo="text",
        marker=dict(size=14, color=node_colors, line=dict(width=1.5, color="white")),
    )

    fig = go.Figure(data=[edge_trace, node_trace])
    fig.update_layout(
        showlegend=False,
        height=600,
        margin=dict(l=10, r=10, t=20, b=10),
        xaxis=dict(visible=False),
        yaxis=dict(visible=False),
    )
    st.plotly_chart(fig, use_container_width=True)